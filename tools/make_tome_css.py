def main():
    css = (CSS.replace('@GRAIN@', GRAIN).replace('@LEATHER@', LEATHER)
           .replace('@PAPERS@', paper_rules()).replace('@SHEET@', sheet(0)))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css)
    print('wrote', OUT, len(css), 'bytes')


