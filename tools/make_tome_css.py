def main():
    css = CSS.replace('@GRAIN@', GRAIN).replace('@LEATHER@', LEATHER).replace('@PAPERS@', paper_rules())
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css)
    print('wrote', OUT, len(css), 'bytes')


if __name__ == '__main__':
    main()
